class Command(BaseCommand):
    help = "Seeds the database with sample student enrollment profiles."

    def handle(self, *args, **options):
        created_count = 0
        for item in SAMPLE_STUDENTS:
            _, created = Student.objects.update_or_create(
                student_id=item["student_id"],
                defaults=item,
            )
            if created:
                created_count += 1
        self.stdout.write(
            self.style.SUCCESS(
                f"Successfully seeded student directory ({created_count} new, {len(SAMPLE_STUDENTS)} total)."
            )
        )
